// Regenerates tactics-library.js from the 战术库 folder.
// Run: node tools/build-tactics-library.mjs
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const libRoot = join(root, '战术库');

// Groups/categories are discovered from the folder tree so categories created
// via the web upload flow are picked up without editing this script.
const entries = [];
let groups = [];
try { groups = readdirSync(libRoot, { withFileTypes: true }).filter(d => d.isDirectory()).map(d => d.name).sort(); } catch {}
for (const group of groups) {
  const groupDir = join(libRoot, group);
  const categories = readdirSync(groupDir, { withFileTypes: true }).filter(d => d.isDirectory()).map(d => d.name).sort();
  for (const category of categories) {
    const dir = join(groupDir, category);
    const files = readdirSync(dir).filter(f => f.endsWith('.json')).sort();
    for (const file of files) {
      const data = JSON.parse(readFileSync(join(dir, file), 'utf8'));
      entries.push({
        group,
        category,
        name: file.replace(/\.json$/, ''),
        frames: Array.isArray(data.frames) ? data.frames.length : 0,
        data,
      });
    }
  }
}

const out = '// Auto-generated by tools/build-tactics-library.mjs — do not edit by hand.\n'
  + 'window.TACTICS_LIBRARY = ' + JSON.stringify(entries) + ';\n';
writeFileSync(join(root, 'tactics-library.js'), out);

// Online manifest read via raw.githubusercontent.com (no API rate limit).
const manifest = {
  tactics: entries.map(({ group, category, name, frames }) => ({
    group, category, name, frames,
    path: ['战术库', group, category, name + '.json'].join('/'),
  })),
};
writeFileSync(join(libRoot, 'index.json'), JSON.stringify(manifest, null, 2) + '\n');
console.log(`tactics-library.js written: ${entries.length} tactics, ${out.length} bytes; 战术库/index.json updated`);